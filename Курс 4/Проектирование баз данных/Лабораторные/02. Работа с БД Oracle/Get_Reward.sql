SELECT LAB2.*, 
       CASE 
           WHEN LAB2.AVG >= 4.5 THEN (AMOUNT * 1.5)
           WHEN 3.5 <= LAB2.AVG AND LAB2.AVG < 4.5 THEN (AMOUNT * 1.25)
           WHEN 2.5 <= LAB2.AVG AND LAB2.AVG < 3.5 THEN (AMOUNT)
           ELSE 0
       END AS REWARD
FROM (
    SELECT TAB.*, 
    (TAB.MATH + TAB.INFO + TAB.LANG) / 3 AS AVG
    FROM KRINKIN_LAB2 TAB
) LAB2
LEFT JOIN KRINKIN_LAB2_BST BST ON BST.YEAR = :Year;